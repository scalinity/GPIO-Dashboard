"""Builds content/controllers/pi5-header.json from the official Raspberry Pi documentation.

Usage (stdlib only):
  gh api "repos/raspberrypi/documentation/contents/<FILE>?ref=<COMMIT>" --jq .content \
    | base64 -d > gpio-on-raspberry-pi.adoc
  python3 -I scripts/reference/pi_header_from_docs.py gpio-on-raspberry-pi.adoc <COMMIT> \
    > src/renderer/src/content/controllers/pi5-header.json

FILE is documentation/asciidoc/computers/raspberry-pi/gpio-on-raspberry-pi.adoc. The script reads
the table "Pin names, types, and typical functions" (one cell per line; a header row on one line)
and refuses to write anything unless it finds exactly pins 1..40.
"""
import json
import re
import sys

SOURCE_FILE = "documentation/asciidoc/computers/raspberry-pi/gpio-on-raspberry-pi.adoc"

text = open(sys.argv[1], encoding="utf-8").read()
commit = sys.argv[2]
start = text.index(".Pin names, types, and typical functions")
end = text.index("|===", text.index("|===", start) + 4)

rows, cells = [], []
for line in text[start:end].splitlines():
    if line.startswith("|===") or line.count("|") > 1:
        continue  # table delimiters and the one-line header row
    if line.startswith("|"):
        cells.append(line[1:].strip())
        if len(cells) == 4:
            rows.append(cells)
            cells = []
    elif line.strip() and cells:
        cells[-1] += " " + line.strip()  # a cell continued on the next line

pins = []
for physical, name, kind, function in rows:
    name = name.strip("`")
    bcm = int(name[2:]) if re.fullmatch(r"GP\d+", name) else None
    pins.append({
        "physical": int(physical),
        "name": name,
        "type": kind,
        "bcm": bcm,
        "function": re.sub(r"\s+", " ", function).strip(),
    })
pins.sort(key=lambda p: p["physical"])
if [p["physical"] for p in pins] != list(range(1, 41)):
    sys.exit("expected pins 1..40")

json.dump({
    "id": "pi5-header",
    "name": "Raspberry Pi 5 40-pin GPIO header",
    "pitchMm": 2.54,
    "provenance": {
        "sources": [
            f"https://github.com/raspberrypi/documentation/blob/{commit}/{SOURCE_FILE}",
            "https://www.raspberrypi.com/documentation/computers/raspberry-pi.html#gpio",
        ],
        "notes": "Generated by scripts/reference/pi_header_from_docs.py from the table "
                 "'Pin names, types, and typical functions'. Pin 1 is at the corner away from "
                 "the USB and Ethernet ports on classic boards (same document, 'Pin layout').",
    },
    "pins": pins,
}, sys.stdout, indent=2, ensure_ascii=False)
sys.stdout.write("\n")
